Para efectos de esta política se aplican las definiciones del artículo 3 de la Ley 1581 de 2012 y del Decreto 1377 de 2013, entre ellas:

- **Autorización:** consentimiento previo, expreso e informado del Titular para llevar a cabo el tratamiento de sus datos personales.
