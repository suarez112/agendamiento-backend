// Splits the legal source file (docs/legal/*.md) into its three documents.
// The file separates them with "# DOCUMENTO N · <title>" headings; the heading line
// gives the title and is not part of the stored text. The trailing "---" separator
// between documents is dropped too. A first line "**Versión X · Vigente(s) desde el
// D de <mes> de AAAA**" gives the effective date and is dropped as well (the app shows
// version and date under the title). Every other character is kept as is.

export type TipoDocumentoLegal = 'politica_datos' | 'terminos' | 'aviso_privacidad';
export type DocumentoLegal = {
  tipo: TipoDocumentoLegal;
  titulo: string;
  contenido: string;
  // AAAA-MM-DD, or null when the document has no "Vigente desde" line (e.g. the short notice)
  vigenteDesde: string | null;
};

const TIPO_POR_NUMERO: Record<string, TipoDocumentoLegal> = {
  '1': 'politica_datos',
  '2': 'terminos',
  '3': 'aviso_privacidad',
};

const ENCABEZADO = /^# DOCUMENTO (\d+) · (.+)$/;
const LINEA_VERSION = /^\*\*Versión (\S+) · Vigentes? desde el (\d{1,2}) de ([a-z]+) de (\d{4})\*\*$/;
const MESES = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre'];

// Reads and removes the version line at the top of a document body
const extraerVigencia = (cuerpo: string, numero: string, version: string) => {
  const [primera = '', ...resto] = cuerpo.split('\n');
  if (!primera.startsWith('**Versión')) return { contenido: cuerpo, vigenteDesde: null };
  const m = LINEA_VERSION.exec(primera);
  if (!m) throw new Error(`Document ${numero}: unrecognized version line: ${primera}`);
  const [, versionLinea, dia, mesTexto, anio] = m;
  if (versionLinea !== version) throw new Error(`Document ${numero} says version ${versionLinea}, expected ${version}`);
  const mes = MESES.indexOf(mesTexto!) + 1;
  const fecha = new Date(Date.UTC(Number(anio), mes - 1, Number(dia)));
  if (!mes || fecha.getUTCDate() !== Number(dia)) throw new Error(`Document ${numero}: invalid date in ${primera}`);
  return { contenido: resto.join('\n').trim(), vigenteDesde: fecha.toISOString().slice(0, 10) };
};

export const separarDocumentosLegales = (md: string, version: string): DocumentoLegal[] => {
  const lineas = md.replace(/\r\n/g, '\n').split('\n');
  const documentos: { numero: string; titulo: string; lineas: string[] }[] = [];
  for (const linea of lineas) {
    const encabezado = ENCABEZADO.exec(linea);
    if (encabezado) documentos.push({ numero: encabezado[1]!, titulo: encabezado[2]!.trim(), lineas: [] });
    else if (documentos.length) documentos.at(-1)!.lineas.push(linea);
    else if (linea.trim()) throw new Error('Text found before "# DOCUMENTO 1"');
  }

  const resultado = documentos.map(({ numero, titulo, lineas: cuerpo }) => {
    const tipo = TIPO_POR_NUMERO[numero];
    if (!tipo) throw new Error(`Unknown document number: ${numero}`);
    const texto = cuerpo.join('\n').trim().replace(/\n+---$/, '').trim();
    const { contenido, vigenteDesde } = extraerVigencia(texto, numero, version);
    if (!contenido) throw new Error(`Document ${numero} is empty`);
    return { tipo, titulo, contenido, vigenteDesde };
  });

  const tipos = resultado.map((d) => d.tipo).join(',');
  if (tipos !== 'politica_datos,terminos,aviso_privacidad') {
    throw new Error(`Expected documents 1, 2 and 3 in order, found: ${tipos}`);
  }
  return resultado;
};

// Builds the SQL migration that publishes the given version of the three documents.
// Uses dollar quoting; refuses to run if a document contains the quote tag.
export const sqlPublicarVersion = (version: string, documentos: DocumentoLegal[], fuente: string) => {
  const etiqueta = '$doc$';
  const literal = (texto: string) => {
    if (texto.includes(etiqueta)) throw new Error(`Text contains ${etiqueta}`);
    return `${etiqueta}${texto}${etiqueta}`;
  };
  if (!/^\d+\.\d+$/.test(version)) throw new Error(`Invalid version: ${version}`);
  const filas = documentos.map(
    (d) =>
      `(\n'${d.tipo}',\n'${version}',\n${d.vigenteDesde ? `'${d.vigenteDesde}'` : 'NULL'},\n${literal(d.titulo)},\n${literal(d.contenido)}\n)`,
  );
  return [
    `-- Version ${version} of the legal documents: Política de Tratamiento de Datos,`,
    '-- Términos y Condiciones and Aviso de privacidad.',
    `-- GENERATED by "npm run legal:generar-migracion" from ${fuente}. Do not edit by hand.`,
    '-- Older versions stay in the table (history of what was accepted); the newest row',
    '-- of each type becomes the current one, so accounts that accepted an older version',
    '-- must accept this one again (legal/estado, debeAceptarDocumentos, next booking).',
    '',
    'INSERT INTO documentos_legales (tipo, version, vigente_desde, titulo, contenido) VALUES',
    `${filas.join(',\n')};`,
    '',
  ].join('\n');
};
